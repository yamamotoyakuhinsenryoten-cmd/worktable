export function buildLogPrompt({
  logType,
  slug,
  conversation,
}: BuildLogPromptArgs) {
  const prompts: Record<LogType, string> = {
    work: workPrompt,
    experience: experiencePrompt,
    development: developmentPrompt,
  };

  return prompts[logType]
    .replaceAll("{{slug}}", slug)
    .replaceAll("{{logType}}", logType)
    .replace(
      "出力はコードブロック内のみにしてください。",
      `入力されたチャット：

${conversation}

出力はコードブロック内のみにしてください。`,
    );
}
